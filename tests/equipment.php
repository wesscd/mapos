<?php

defined('BASEPATH') or exit('No direct script access allowed');

$ci->load->library('equipamento_service');
$equipmentService = $ci->equipamento_service;
$equipmentData = ['clientes_id' => $customer, 'equipamento' => 'Notebook teste', 'marca' => 'Marca teste', 'modelo' => 'Modelo A', 'num_serie' => 'SN-TESTE'];
$equipmentId = $equipmentService->save($equipmentData);
$assert($equipmentService->get($equipmentId)->marca === 'Marca teste', 'Equipment catalog reuses brands and preserves the customer owner');
$reject(fn () => $equipmentService->save(array_merge($equipmentData, ['equipamento' => ['invalid']])), 'Equipment validation rejects non-scalar fields');
$equipmentOrder = $create();
$linkId = $equipmentService->link($equipmentOrder, $equipmentId);
$assert($equipmentService->link($equipmentOrder, $equipmentId) === $linkId, 'Repeated linking is idempotent');
$assert(! $db->get_where('equipamento_recibos', ['vinculo_id' => $linkId])->row(), 'Linking a catalog record never implies physical intake');
$foreignData = array_merge($equipmentData, ['clientes_id' => 1]);
// The preinstalled client may have id=1; create an explicit second owner instead.
$db->insert('clientes', ['nomeCliente' => 'Outro cliente', 'documento' => 'TEST-OTHER', 'telefone' => '000', 'email' => 'other@example.test']);
$foreignData['clientes_id'] = $db->insert_id();
$foreignEquipment = $equipmentService->save($foreignData);
$reject(fn () => $equipmentService->link($equipmentOrder, $foreignEquipment), 'An OS cannot link equipment from another customer');
$reject(fn () => $equipmentService->save($foreignData, $equipmentId), 'Equipment with service history cannot change owners');
$reject(fn () => $workflow->updateOrder($equipmentOrder, ['clientes_id' => $foreignData['clientes_id'], 'status' => 'Aberto'], false), 'OS customer changes cannot strand linked equipment under a different owner');
$intakeData = ['acessorios' => 'Carregador', 'condicoes' => 'Risco na tampa', 'entregue_por' => 'Cliente Teste'];
$reject(fn () => $equipmentService->intake($other, $linkId, $intakeData), 'Intake verifies that the link belongs to the requested OS');
$reject(fn () => $equipmentService->intake($equipmentOrder, $linkId, array_merge($intakeData, ['condicoes' => ''])), 'Physical intake requires an explicit condition report');
$reject(fn () => $equipmentService->photo($equipmentId, '<svg onload="alert(1)"></svg>'), 'Equipment photos reject executable image formats');
$image = imagecreatetruecolor(12, 12);
ob_start();
imagepng($image);
$bytes = ob_get_clean();
imagedestroy($image);
$photoId = $equipmentService->photo($equipmentId, $bytes);
$storedPhoto = $db->get_where('equipamento_fotos', ['id' => $photoId])->row();
$assert(getimagesizefromstring($storedPhoto->imagem)[2] === IMAGETYPE_JPEG, 'Photos are decoded and reencoded before private storage');
$receiptId = $equipmentService->intake($equipmentOrder, $linkId, $intakeData);
$entry = $db->get_where('equipamento_recibos', ['id' => $receiptId])->row();
$snapshot = json_decode($entry->dados, true);
$assert($snapshot['serie'] === 'SN-TESTE' && $snapshot['fotos'] === [$photoId], 'Intake snapshots identity, accessories, conditions and existing photos');
$parallelOrder = $create();
$parallelLink = $equipmentService->link($parallelOrder, $equipmentId);
$reject(fn () => $equipmentService->intake($parallelOrder, $parallelLink, $intakeData), 'An equipment cannot be physically received twice without its previous pickup');
$equipmentService->save(array_merge($equipmentData, ['num_serie' => 'SN-EDITED']), $equipmentId);
$equipmentService->photo($equipmentId, $bytes);
$assert($db->get_where('equipamento_recibos', ['id' => $receiptId])->row()->dados === $entry->dados, 'Later catalog edits and photos do not rewrite an existing receipt');
$reject(fn () => $equipmentService->intake($equipmentOrder, $linkId, $intakeData), 'A repeated intake cannot overwrite the first receipt');
$reject(fn () => $workflow->deleteOrder($equipmentOrder, false), 'Physical receipts prevent deletion of their service history');
$db->where('idOs', $equipmentOrder)->update('os', ['status' => 'Finalizado']);
$reject(fn () => $workflow->deliver($equipmentOrder), 'Documented equipment requires the pickup recipient before delivery');
$assert(! $db->get_where('os', ['idOs' => $equipmentOrder])->row()->entregue_em, 'Rejected delivery leaves the OS undelivered');
$workflow->deliver($equipmentOrder, 'Pessoa autorizada');
$exit = $db->get_where('equipamento_recibos', ['vinculo_id' => $linkId, 'tipo' => 'saida'])->row();
$assert(json_decode($exit->dados, true)['retirado_por'] === 'Pessoa autorizada' && $db->get_where('os', ['idOs' => $equipmentOrder])->row()->entregue_em, 'Pickup receipt and OS delivery commit together');
$reject(fn () => $workflow->deliver($equipmentOrder, 'Outra pessoa'), 'A second delivery cannot issue duplicate receipts');
$reject(fn () => $workflow->updateOrder($equipmentOrder, ['status' => 'Aberto'], false), 'A documented delivery is preserved when equipment returns for a new service');
$notReceivedOrder = $create();
$equipmentService->link($notReceivedOrder, $equipmentId);
$db->where('idOs', $notReceivedOrder)->update('os', ['status' => 'Finalizado']);
$reject(fn () => $workflow->deliver($notReceivedOrder, 'Cliente'), 'Linked equipment without physical intake cannot produce a misleading delivery');
$qr = new \Mpdf\QrCode\QrCode(site_url('equipamentos/visualizar/' . $equipmentId));
$assert(getimagesizefromstring((new \Mpdf\QrCode\Output\Png())->output($qr, 240))[0] === 240, 'Equipment labels render a QR pointing to the authenticated catalog');
$cancelledReceipt = $equipmentService->intake($parallelOrder, $parallelLink, $intakeData);
$db->where('idOs', $parallelOrder)->update('os', ['status' => 'Cancelado']);
$workflow->deliver($parallelOrder, 'Cliente');
$assert((bool) $db->get_where('os', ['idOs' => $parallelOrder])->row()->entregue_em, 'Cancelled services can still document the return of equipment already received');
$newOrderData = ['clientes_id' => $customer, 'usuarios_id' => 1, 'status' => 'Aberto', 'faturado' => 0];
$orderWithEquipment = $workflow->createOrder($newOrderData, [$equipmentId, $equipmentId]);
$assert($db->where('os_id', $orderWithEquipment)->count_all_results('equipamentos_os') === 1, 'New OS creation saves its selected equipment atomically without duplicate links');
$assert(! $db->from('equipamento_recibos')->join('equipamentos_os', 'equipamentos_os.idEquipamentos_os = equipamento_recibos.vinculo_id')->where('os_id', $orderWithEquipment)->count_all_results(), 'Selecting equipment when opening an OS does not confirm physical receipt');
$beforeCreate = [$db->count_all('os'), $db->count_all('os_eventos'), $db->count_all('com_fila')];
$reject(fn () => $workflow->createOrder($newOrderData, [$equipmentId, $foreignEquipment]), 'New OS creation rejects equipment owned by another customer');
$assert($beforeCreate === [$db->count_all('os'), $db->count_all('os_eventos'), $db->count_all('com_fila')], 'Invalid equipment selection rolls back the OS, timeline and notification outbox together');
$reject(fn () => $workflow->createOrder($newOrderData, [['invalid']]), 'New OS creation rejects malformed equipment identifiers');
